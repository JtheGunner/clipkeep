private final class FakePasteboard: PasteboardReading, @unchecked Sendable {
    private let lock = NSLock()
    private var current: PasteboardSnapshot

    init(_ snapshot: PasteboardSnapshot = PasteboardSnapshot(changeCount: 1)) { current = snapshot }

    var changeCount: Int { lock.withLock { current.changeCount } }
    private var results: [PasteboardSnapshot?] = []
    /// Snapshots handed out first (nil simulates a copy landing mid-read).
    func queue(_ values: [PasteboardSnapshot?]) { lock.withLock { results = values } }
    func snapshot() -> PasteboardSnapshot? {
        lock.withLock { results.isEmpty ? current : results.removeFirst() }
    }
    func set(_ snapshot: PasteboardSnapshot) { lock.withLock { current = snapshot } }
}

private struct FakeSource: SourceAppProviding {
    var contexts = [CopyContext(appBundleID: "com.example.editor", appName: "Editor")]
    func sources(from start: Date, to end: Date) -> [CopyContext] { contexts }
}

private final class WindowRecorder: SourceAppProviding, @unchecked Sendable {
    private let lock = NSLock()
    private var starts: [Date] = []
    var windowStarts: [Date] { lock.withLock { starts } }
    func sources(from start: Date, to end: Date) -> [CopyContext] {
        lock.withLock { starts.append(start) }
        return [CopyContext(appBundleID: "com.example.editor")]
    }
}

private final class RecordingSink: SecretSink, @unchecked Sendable {
    private let lock = NSLock()
    private var received: [String] = []
    var texts: [String] { lock.withLock { received } }
    func handle(secret text: String, context: CopyContext, copiedAt: Date) {
        lock.withLock { received.append(text) }
    }
}

private final class ErrorLog: @unchecked Sendable {
    private let lock = NSLock()
    private var count = 0
    var errors: Int { lock.withLock { count } }
    func add() { lock.withLock { count += 1 } }
}

@Suite struct CaptureStageTests {
    private let configuration = CaptureConfiguration()
    private let editor = CopyContext(appBundleID: "com.example.editor")

    @Test(arguments: [
        ("org.nspasteboard.ConcealedType", SkipReason.concealed),
        ("com.agilebits.onepassword", SkipReason.concealed),
        ("org.nspasteboard.TransientType", SkipReason.transient),
        ("org.nspasteboard.AutoGeneratedType", SkipReason.autoGenerated),
    ])
    func markedTypesAreSkipped(type: String, expected: SkipReason) {
        let snapshot = PasteboardSnapshot(changeCount: 1, types: [type, "public.utf8-plain-text"])
        #expect(
            CaptureStages.skipReason(for: snapshot, source: editor, configuration: configuration)
                == expected)
    }

    @Test func passwordManagersAreBlockedByDefault() {
        let snapshot = PasteboardSnapshot(changeCount: 1, types: ["public.utf8-plain-text"])
        let bitwarden = CopyContext(appBundleID: "com.bitwarden.desktop")
        #expect(
            CaptureStages.skipReason(for: snapshot, source: bitwarden, configuration: configuration)
                == .blockedApp)
        #expect(
            CaptureStages.skipReason(for: snapshot, source: editor, configuration: configuration)
                == nil)
        #expect(
            CaptureStages.skipReason(
                for: snapshot, source: CopyContext(), configuration: configuration) == nil)
    }

    @Test func blacklistIsConfigurable() {
        let custom = CaptureConfiguration(blockedBundleIDs: ["com.example.editor"])
        let snapshot = PasteboardSnapshot(changeCount: 1)
        #expect(
            CaptureStages.skipReason(for: snapshot, source: editor, configuration: custom)
                == .blockedApp)
        #expect(
            CaptureStages.skipReason(
                for: snapshot, source: CopyContext(appBundleID: "com.bitwarden.desktop"),
                configuration: custom) == nil)
    }

    @Test func contentPrefersTextThenUrlsThenPaths() {
        #expect(
            CaptureStages.content(
                of: PasteboardSnapshot(
                    changeCount: 1, text: "hello", urls: ["https://example.com"], filePaths: ["/a"])
            )
                == "hello")
        #expect(
            CaptureStages.content(
                of: PasteboardSnapshot(
                    changeCount: 1, urls: ["https://a.example", "https://b.example"]))
                == "https://a.example\nhttps://b.example")
        #expect(
            CaptureStages.content(
                of: PasteboardSnapshot(changeCount: 1, filePaths: ["/tmp/a", "/tmp/b"]))
                == "/tmp/a\n/tmp/b")
        #expect(CaptureStages.content(of: PasteboardSnapshot(changeCount: 1, text: "")) == nil)
        #expect(CaptureStages.content(of: PasteboardSnapshot(changeCount: 1)) == nil)
    }

    @Test func normalizeUnifiesLineEndingsAndTrims() {
        #expect(CaptureStages.normalize("  a\r\nb\rc \n\n") == "a\nb\nc")
        #expect(CaptureStages.normalize(" \n\t ") == "")
        #expect(CaptureStages.normalize("keep  inner   spaces") == "keep  inner   spaces")
    }

    @Test func lengthLimits() {
        #expect(CaptureStages.lengthSkip(of: "", configuration: configuration) == .empty)
        #expect(CaptureStages.lengthSkip(of: "a", configuration: configuration) == .tooShort)
        #expect(CaptureStages.lengthSkip(of: "ab", configuration: configuration) == nil)
        let small = CaptureConfiguration(minimumLength: 2, maximumLength: 5)
        #expect(CaptureStages.lengthSkip(of: "abcdef", configuration: small) == .tooLong)
        #expect(CaptureStages.lengthSkip(of: "abcde", configuration: small) == nil)
    }
}

@Suite struct CapturePipelineTests {
    private let base = Date(timeIntervalSince1970: 1_800_000_000)
    private let editor = CopyContext(appBundleID: "com.example.editor", appName: "Editor")

    private struct Fixture {
        let temp: TemporaryDatabase
        let database: Database
        let pipeline: CapturePipeline
        let sink = RecordingSink()

        init(configuration: CaptureConfiguration = CaptureConfiguration()) throws {
            temp = try TemporaryDatabase()
            database = try temp.open()
            pipeline = CapturePipeline(
                store: ContentStore(database: database), configuration: configuration,
                secretSink: sink)
        }

        func count(_ table: String) throws -> Int64 {
            try database.read {
                try $0.query("SELECT count(*) FROM \(table)") { $0.int(0) }.first ?? 0
            }
        }
    }

    private func text(_ value: String, count: Int = 1, types: Set<String> = [])
        -> PasteboardSnapshot
    {
        PasteboardSnapshot(changeCount: count, types: types, text: value)
    }

    @Test func aCopyCreatesExactlyOneEntry() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        let outcome = try fixture.pipeline.process(
            text("hello clipboard"), source: editor, at: base)
        guard case .recorded(let copy) = outcome else {
            Issue.record("Expected a recorded copy, got \(outcome)")
            return
        }
        #expect(copy.isNewContent)
        #expect(try fixture.count("contents") == 1)
        #expect(try fixture.count("copy_events") == 1)
        let context = try fixture.database.read {
            try $0.query("SELECT app_bundle_id, app_name FROM copy_events") {
                [$0.text(0), $0.text(1)]
            }.first
        }
        #expect(context == ["com.example.editor", "Editor"])
    }

    @Test func concealedAndTransientContentIsNeverStored() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        for type in [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            let outcome = try fixture.pipeline.process(
                text("top secret words here", types: [type]), source: editor, at: base)
            #expect(
                outcome == .skipped(.concealed) || outcome == .skipped(.transient)
                    || outcome == .skipped(.autoGenerated))
        }
        #expect(try fixture.count("contents") == 0)
        #expect(try fixture.count("copy_events") == 0)
    }

    @Test func blockedAppsAreNeverStored() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        let outcome = try fixture.pipeline.process(
            text("vault entry name"), source: CopyContext(appBundleID: "com.bitwarden.desktop"),
            at: base)
        #expect(outcome == .skipped(.blockedApp))
        #expect(try fixture.count("contents") == 0)
    }

    @Test func emptyAndShortContentIsDropped() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        #expect(try fixture.pipeline.process(text("  \r\n "), source: editor) == .skipped(.empty))
        #expect(try fixture.pipeline.process(text("x"), source: editor) == .skipped(.tooShort))
        #expect(
            try fixture.pipeline.process(PasteboardSnapshot(changeCount: 1), source: editor)
                == .skipped(.noText))
        #expect(try fixture.count("contents") == 0)
    }

    @Test func differentlyFormattedCopiesOfTheSameTextShareOneContent() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        _ = try fixture.pipeline.process(text("line one\r\nline two"), source: editor, at: base)
        _ = try fixture.pipeline.process(
            text("  line one\nline two\n"), source: editor, at: base.addingTimeInterval(5))
        #expect(try fixture.count("contents") == 1)
        #expect(try fixture.count("copy_events") == 2)
    }

    @Test func urlsAndPathsAreStoredAsText() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        _ = try fixture.pipeline.process(
            PasteboardSnapshot(changeCount: 1, urls: ["https://example.com/a"]), source: editor)
        _ = try fixture.pipeline.process(
            PasteboardSnapshot(changeCount: 2, filePaths: ["/Users/example/notes.txt"]),
            source: editor)
        let stored = try fixture.database.read {
            try $0.query("SELECT text FROM contents ORDER BY id") { $0.text(0) }
        }
        #expect(stored == ["https://example.com/a", "/Users/example/notes.txt"])
    }

    @Test func detectedSecretsAreNotStoredAndReachTheSink() throws {
        let fixture = try Fixture()
        defer { fixture.temp.remove() }
        let secret = "ghp_" + String(repeating: "aB3dE6gH9k", count: 3) + "xyz012"
        let outcome = try fixture.pipeline.process(text("token=\(secret)"), source: editor)
        #expect(outcome == .skipped(.secret))
        #expect(fixture.sink.texts == ["token=\(secret)"])
        #expect(try fixture.count("contents") == 0)
        #expect(try fixture.count("copy_events") == 0)
    }
}

@Suite struct ClipboardPollerTests {
    private let base = Date(timeIntervalSince1970: 1_800_000_000)

    private func makePoller(
        pasteboard: FakePasteboard, database: Database,
        onError: @escaping @Sendable (Error) -> Void = { _ in }
    ) -> ClipboardPoller {
        ClipboardPoller(
            pasteboard: pasteboard, source: FakeSource(),
            pipeline: CapturePipeline(store: ContentStore(database: database)), onError: onError)
    }

    @Test func unchangedPasteboardProducesNothingAndStartContentIsNotCaptured() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let pasteboard = FakePasteboard(PasteboardSnapshot(changeCount: 5, text: "already there"))
        let errorLog = ErrorLog()
        let poller = makePoller(
            pasteboard: pasteboard, database: try temp.open(), onError: { _ in errorLog.add() })
        #expect(poller.poll(now: base) == nil)
        #expect(poller.poll(now: base) == nil)
        #expect(try Self.count("contents", temp) == 0)
        #expect(errorLog.errors == 0)
    }

    private static func count(_ table: String, _ temp: TemporaryDatabase) throws -> Int64 {
        try temp.open().read {
            try $0.query("SELECT count(*) FROM \(table)") { $0.int(0) }.first ?? 0
        }
    }

    @Test func eachChangeIsCapturedOnce() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let database = try temp.open()
        let pasteboard = FakePasteboard()
        let poller = makePoller(pasteboard: pasteboard, database: database)

        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "first copy"))
        guard case .recorded = poller.poll(now: base) else {
            Issue.record("Expected the first change to be recorded")
            return
        }
        #expect(poller.poll(now: base.addingTimeInterval(1)) == nil)

        // Copying the same text again bumps the change count and is a new event.
        pasteboard.set(PasteboardSnapshot(changeCount: 3, text: "first copy"))
        guard case .recorded(let again) = poller.poll(now: base.addingTimeInterval(2)) else {
            Issue.record("Expected the repeat copy to be recorded")
            return
        }
        #expect(!again.isNewContent)
        let counts = try database.read {
            try $0.query(
                "SELECT (SELECT count(*) FROM contents), (SELECT count(*) FROM copy_events)"
            ) {
                [$0.int(0), $0.int(1)]
            }.first
        }
        #expect(counts == [1, 2])
    }

    @Test func storageErrorsAreReportedAndPollingContinues() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let errors = ErrorLog()
        let pasteboard = FakePasteboard()
        let poller = makePoller(
            pasteboard: pasteboard, database: try temp.open(migrated: false),
            onError: { _ in errors.add() })

        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "lost copy"))
        #expect(poller.poll(now: base) == nil)
        pasteboard.set(PasteboardSnapshot(changeCount: 3, text: "next copy"))
        #expect(poller.poll(now: base) == nil)
        #expect(errors.errors == 2)
    }
    @Test func aCopyThatLandsMidReadIsPickedUpByTheNextPoll() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let database = try temp.open()
        let pasteboard = FakePasteboard()
        let poller = makePoller(pasteboard: pasteboard, database: database)
        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "settled copy"))
        pasteboard.queue([nil])
        #expect(poller.poll(now: base) == nil)
        guard case .recorded = poller.poll(now: base.addingTimeInterval(1)) else {
            Issue.record("Expected the retry to record the copy")
            return
        }
        let events = try database.read {
            try $0.query("SELECT count(*) FROM copy_events") { $0.int(0) }.first
        }
        #expect(events == 1)
    }

    @Test func aFailedSnapshotKeepsTheAttributionWindowOpen() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let pasteboard = FakePasteboard()
        let recorder = WindowRecorder()
        let poller = ClipboardPoller(
            pasteboard: pasteboard, source: recorder,
            pipeline: CapturePipeline(store: ContentStore(database: try temp.open())), now: base)
        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "racy copy"))
        pasteboard.queue([nil])
        poller.poll(now: base.addingTimeInterval(1))
        poller.poll(now: base.addingTimeInterval(2))
        #expect(recorder.windowStarts == [base])
    }

    @Test func aBlockedAppAnywhereInThePollWindowBlocksTheCopy() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let database = try temp.open()
        let pasteboard = FakePasteboard()
        let history = [
            CopyContext(appBundleID: "com.bitwarden.desktop"),
            CopyContext(appBundleID: "com.apple.Safari"),
        ]
        let poller = ClipboardPoller(
            pasteboard: pasteboard, source: FakeSource(contexts: history),
            pipeline: CapturePipeline(store: ContentStore(database: database)))
        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "vault username"))
        #expect(poller.poll(now: base) == .skipped(.blockedApp))
    }

    @Test func aCopyIsAttributedToTheOldestAppOfThePollWindow() throws {
        let temp = try TemporaryDatabase()
        defer { temp.remove() }
        let database = try temp.open()
        let pasteboard = FakePasteboard()
        let history = [
            CopyContext(appBundleID: "com.example.editor", appName: "Editor"),
            CopyContext(appBundleID: "com.apple.Safari", appName: "Safari"),
        ]
        let poller = ClipboardPoller(
            pasteboard: pasteboard, source: FakeSource(contexts: history),
            pipeline: CapturePipeline(store: ContentStore(database: database)))
        pasteboard.set(PasteboardSnapshot(changeCount: 2, text: "copied in the editor"))
        poller.poll(now: base)
        let app = try database.read {
            try $0.query("SELECT app_bundle_id FROM copy_events") { $0.text(0) }.first
        }
        #expect(app == "com.example.editor")
    }
}

@Suite struct CaptureEdgeCaseTests {
    private let editor = CopyContext(appBundleID: "com.example.editor")

    private func pipeline(
        _ sink: RecordingSink, configuration: CaptureConfiguration = CaptureConfiguration()
    ) throws -> (CapturePipeline, TemporaryDatabase) {
        let temp = try TemporaryDatabase()
        let store = ContentStore(database: try temp.open())
        return (CapturePipeline(store: store, configuration: configuration, secretSink: sink), temp)
    }

    private var secret: String { "ghp_" + String(repeating: "aB3dE6gH9k", count: 3) + "xyz012" }

    @Test func skippedCopiesNeverReachTheSecretSink() throws {
        let sink = RecordingSink()
        let (pipeline, temp) = try pipeline(sink)
        defer { temp.remove() }
        let concealed = PasteboardSnapshot(
            changeCount: 1, types: ["org.nspasteboard.ConcealedType"], text: secret)
        #expect(try pipeline.process(concealed, source: editor) == .skipped(.concealed))
        let fromVault = PasteboardSnapshot(changeCount: 2, text: secret)
        #expect(
            try pipeline.process(
                fromVault, source: CopyContext(appBundleID: "com.bitwarden.desktop"))
                == .skipped(.blockedApp))
        _ = try pipeline.process(
            PasteboardSnapshot(changeCount: 3, text: "plain note"), source: editor)
        #expect(sink.texts.isEmpty)
    }

    @Test func tooLongContentIsDroppedBeforeAnyCopy() throws {
        let (pipeline, temp) = try pipeline(
            RecordingSink(),
            configuration: CaptureConfiguration(minimumLength: 2, maximumLength: 10))
        defer { temp.remove() }
        let long = PasteboardSnapshot(changeCount: 1, text: String(repeating: "a", count: 11))
        #expect(try pipeline.process(long, source: editor) == .skipped(.tooLong))
        let huge = PasteboardSnapshot(changeCount: 2, text: String(repeating: "a", count: 41))
        #expect(try pipeline.process(huge, source: editor) == .skipped(.tooLong))
    }

    @Test func configurationClampsItsLimits() {
        let configuration = CaptureConfiguration(minimumLength: 0, maximumLength: -5)
        #expect(configuration.minimumLength == 1)
        #expect(configuration.maximumLength == 1)
    }

    @Test func emptyTextFallsBackToUrls() {
        let snapshot = PasteboardSnapshot(changeCount: 1, text: "", urls: ["https://example.com"])
        #expect(CaptureStages.content(of: snapshot) == "https://example.com")
    }

    @Test func finderFileCopiesStorePathsInsteadOfNames() {
        let single = PasteboardSnapshot(
            changeCount: 1, text: "notes.txt", filePaths: ["/Users/example/notes.txt"])
        #expect(CaptureStages.content(of: single) == "/Users/example/notes.txt")
        let several = PasteboardSnapshot(
            changeCount: 2, text: "a.txt\nb.txt", filePaths: ["/tmp/a.txt", "/tmp/b.txt"])
        #expect(CaptureStages.content(of: several) == "/tmp/a.txt\n/tmp/b.txt")
        let unrelated = PasteboardSnapshot(
            changeCount: 3, text: "real text", filePaths: ["/tmp/a.txt"])
        #expect(CaptureStages.content(of: unrelated) == "real text")
    }

    @Test func extraMarkerTypesAreHonoured() {
        let transient = Set(["de.petermaurer.TransientPasteboardType"])
        #expect(CaptureConfiguration.skipReason(forTypes: transient) == .transient)
        #expect(
            CaptureConfiguration.skipReason(forTypes: [
                "net.antelle.keeweb", "Pasteboard generator type",
            ])
                == .concealed)
        #expect(CaptureConfiguration.skipReason(forTypes: ["public.utf8-plain-text"]) == nil)
    }

    @Test func unicodeLineSeparatorsBecomeNewlines() {
        #expect(CaptureStages.normalize("a\u{2028}b\u{85}c") == "a\nb\nc")
    }
}

@Suite struct SystemPasteboardTests {
    private func makePasteboard() -> NSPasteboard { NSPasteboard.withUniqueName() }

    @Test func readsTextAndTypes() {
        let board = makePasteboard()
        defer { board.releaseGlobally() }
        board.clearContents()
        board.setString("hello from a test", forType: .string)
        let snapshot = SystemPasteboard(pasteboard: board).snapshot()
        #expect(snapshot?.text == "hello from a test")
        #expect(snapshot?.changeCount == board.changeCount)
        #expect(snapshot?.types.contains("public.utf8-plain-text") == true)
    }

    @Test func concealedContentIsNotReadIntoTheSnapshot() {
        let board = makePasteboard()
        defer { board.releaseGlobally() }
        board.clearContents()
        board.setString("vault password", forType: .string)
        board.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        let snapshot = SystemPasteboard(pasteboard: board).snapshot()
        #expect(snapshot?.text == nil)
        #expect(snapshot?.types.contains("org.nspasteboard.ConcealedType") == true)
    }

    @Test func readsFileUrlsAsPathsAndWebUrlsAsUrls() throws {
        let board = makePasteboard()
        defer { board.releaseGlobally() }
        board.clearContents()
        let file = URL(fileURLWithPath: "/tmp/clipkeep-test-a.txt")
        let web = try #require(URL(string: "https://example.com/page"))
        #expect(board.writeObjects([file as NSURL, web as NSURL]))
        let snapshot = try #require(SystemPasteboard(pasteboard: board).snapshot())
        #expect(snapshot.filePaths == ["/tmp/clipkeep-test-a.txt"])
        #expect(snapshot.urls == ["https://example.com/page"])
    }

    @Test func trackerAttributesToTheAppActiveAtTheStartOfTheWindow() {
        let base = Date(timeIntervalSince1970: 1_800_000_000)
        let tracker = FrontmostApplicationTracker(now: base)
        let editor = CopyContext(appBundleID: "com.example.editor")
        let browser = CopyContext(appBundleID: "com.example.browser")
        tracker.record(editor, at: base.addingTimeInterval(1))
        tracker.record(browser, at: base.addingTimeInterval(2.2))
        let window = tracker.sources(
            from: base.addingTimeInterval(1.5), to: base.addingTimeInterval(2.5))
        #expect(window == [editor, browser])
        #expect(
            tracker.sources(from: base.addingTimeInterval(3), to: base.addingTimeInterval(4)) == [
                browser
            ])
    }
}
