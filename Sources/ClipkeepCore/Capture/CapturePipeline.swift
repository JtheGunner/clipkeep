import Foundation

public struct CaptureConfiguration: Sendable, Equatable {
    /// Bundle identifiers of apps whose copies are never stored (password managers).
    public static let defaultBlockedBundleIDs: Set<String> = [
        "com.bitwarden.desktop", "com.1password.1password", "com.1password.1password7",
        "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "org.keepassxc.keepassxc",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
        "com.apple.keychainaccess", "com.apple.Passwords",
    ]
    /// Pasteboard types that mark a copy as not meant to be kept.
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public var blockedBundleIDs: Set<String>
    public var minimumLength: Int
    public var maximumLength: Int

    public init(
        blockedBundleIDs: Set<String> = defaultBlockedBundleIDs, minimumLength: Int = 2,
        maximumLength: Int = 1_000_000
    ) {
        self.blockedBundleIDs = blockedBundleIDs
        self.minimumLength = max(minimumLength, 1)
        self.maximumLength = max(maximumLength, self.minimumLength)
    }
}

public enum SkipReason: String, Sendable, Equatable {
    case concealed, transient, autoGenerated
    case blockedApp
    case noText, empty, tooShort, tooLong
    case secret
}

public enum CaptureOutcome: Sendable, Equatable {
    case recorded(RecordedCopy)
    case skipped(SkipReason)
}

/// Receives text the detector flagged as a secret. Nothing is stored for it by the pipeline;
/// a sink may park the value somewhere safe (see the Keychain parking task).
public protocol SecretSink: Sendable {
    func handle(secret text: String, context: CopyContext, copiedAt: Date)
}

/// The capture pipeline as single stages that can be tested one by one.
public enum CaptureStages {
    /// Why a copy must not be stored based on its pasteboard types and source app, if so.
    public static func skipReason(
        for snapshot: PasteboardSnapshot, source: CopyContext, configuration: CaptureConfiguration
    ) -> SkipReason? {
        if snapshot.types.contains("org.nspasteboard.ConcealedType")
            || snapshot.types.contains("com.agilebits.onepassword")
        {
            return .concealed
        }
        if snapshot.types.contains("org.nspasteboard.TransientType") { return .transient }
        if snapshot.types.contains("org.nspasteboard.AutoGeneratedType") { return .autoGenerated }
        if let bundleID = source.appBundleID, configuration.blockedBundleIDs.contains(bundleID) {
            return .blockedApp
        }
        return nil
    }

    /// Plain text first, then URLs, then file paths, one per line.
    public static func content(of snapshot: PasteboardSnapshot) -> String? {
        if let text = snapshot.text, !text.isEmpty { return text }
        if !snapshot.urls.isEmpty { return snapshot.urls.joined(separator: "\n") }
        if !snapshot.filePaths.isEmpty { return snapshot.filePaths.joined(separator: "\n") }
        return nil
    }

    /// Unifies line endings to `\n` and trims surrounding whitespace.
    public static func normalize(_ text: String) -> String {
        text.replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Length checks on normalized text.
    public static func lengthSkip(of text: String, configuration: CaptureConfiguration)
        -> SkipReason?
    {
        if text.isEmpty { return .empty }
        let count = text.count
        if count < configuration.minimumLength { return .tooShort }
        if count > configuration.maximumLength { return .tooLong }
        return nil
    }
}

/// Turns one pasteboard snapshot into at most one stored copy.
public struct CapturePipeline: Sendable {
    private let store: ContentStore
    private let configuration: CaptureConfiguration
    private let detector: SecretDetector
    private let secretSink: (any SecretSink)?

    public init(
        store: ContentStore, configuration: CaptureConfiguration = CaptureConfiguration(),
        detector: SecretDetector = SecretDetector(), secretSink: (any SecretSink)? = nil
    ) {
        self.store = store
        self.configuration = configuration
        self.detector = detector
        self.secretSink = secretSink
    }

    public func process(
        _ snapshot: PasteboardSnapshot, source: CopyContext, at copiedAt: Date = Date()
    ) throws -> CaptureOutcome {
        if let reason = CaptureStages.skipReason(
            for: snapshot, source: source, configuration: configuration)
        {
            return .skipped(reason)
        }
        guard let raw = CaptureStages.content(of: snapshot) else { return .skipped(.noText) }
        let text = CaptureStages.normalize(raw)
        if let reason = CaptureStages.lengthSkip(of: text, configuration: configuration) {
            return .skipped(reason)
        }
        if detector.containsSecret(in: text) {
            secretSink?.handle(secret: text, context: source, copiedAt: copiedAt)
            return .skipped(.secret)
        }
        return .recorded(try store.record(text: text, copiedAt: copiedAt, context: source))
    }
}
