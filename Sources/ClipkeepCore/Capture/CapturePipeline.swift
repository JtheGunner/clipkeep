import Foundation

public struct CaptureConfiguration: Sendable, Equatable {
    /// Bundle identifiers of apps whose copies are never stored (password managers).
    public static let defaultBlockedBundleIDs: Set<String> = [
        "com.bitwarden.desktop", "com.1password.1password", "com.1password.1password7",
        "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "org.keepassxc.keepassxc",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
        "com.apple.keychainaccess", "com.apple.Passwords",
    ]
    /// Pasteboard types that mark a copy as not meant to be kept, and why.
    public static let markerTypes: [String: SkipReason] = [
        "org.nspasteboard.ConcealedType": .concealed,
        "com.agilebits.onepassword": .concealed,
        "net.antelle.keeweb": .concealed,
        "org.nspasteboard.TransientType": .transient,
        "de.petermaurer.TransientPasteboardType": .transient,
        "org.nspasteboard.AutoGeneratedType": .autoGenerated,
        "com.typeit4me.clipping": .autoGenerated,
        "Pasteboard generator type": .autoGenerated,
    ]

    /// Why a copy with these pasteboard types must not be stored, if so. Concealed wins over the
    /// other reasons.
    public static func skipReason(forTypes types: Set<String>) -> SkipReason? {
        let reasons = types.compactMap { markerTypes[$0] }
        for reason in [SkipReason.concealed, .transient, .autoGenerated]
        where reasons.contains(reason) {
            return reason
        }
        return nil
    }

    public var blockedBundleIDs: Set<String>
    public var minimumLength: Int
    public var maximumLength: Int

    public init(
        blockedBundleIDs: Set<String> = defaultBlockedBundleIDs, minimumLength: Int = 2,
        maximumLength: Int = 1_000_000
    ) {
        self.blockedBundleIDs = blockedBundleIDs
        self.minimumLength = max(minimumLength, 1)
        self.maximumLength = max(maximumLength, self.minimumLength)
    }
}

public enum SkipReason: String, Sendable, Equatable {
    case concealed, transient, autoGenerated
    case blockedApp
    case paused, ignoredByRule
    case noText, empty, tooShort, tooLong
    case secret
}

public enum CaptureOutcome: Sendable, Equatable {
    case recorded(RecordedCopy)
    case skipped(SkipReason)
}

/// Receives text the detector flagged as a secret. Nothing is stored for it by the pipeline;
/// a sink may park the value somewhere safe (see the Keychain parking task).
public protocol SecretSink: Sendable {
    func handle(secret text: String, context: CopyContext, copiedAt: Date)
}

/// The capture pipeline as single stages that can be tested one by one.
public enum CaptureStages {
    /// Why a copy must not be stored based on its pasteboard types and source app, if so.
    public static func skipReason(
        for snapshot: PasteboardSnapshot, source: CopyContext, configuration: CaptureConfiguration
    ) -> SkipReason? {
        if let reason = CaptureConfiguration.skipReason(forTypes: snapshot.types) { return reason }
        if let bundleID = source.appBundleID, configuration.blockedBundleIDs.contains(bundleID) {
            return .blockedApp
        }
        return nil
    }

    /// Most file paths joined into one entry; a huge Finder selection is cut off here.
    static let maximumPaths = 1_000

    /// Plain text first, then URLs, then file paths, one per line. Finder puts only the file
    /// names on the pasteboard as text next to the file URLs; the paths are more useful then.
    public static func content(of snapshot: PasteboardSnapshot) -> String? {
        let paths = snapshot.filePaths.prefix(maximumPaths).joined(separator: "\n")
        if let text = snapshot.text, !text.isEmpty {
            let names = snapshot.filePaths.map { ($0 as NSString).lastPathComponent }
            let isFileNameText =
                !names.isEmpty
                && (text == names.joined(separator: "\n") || names.contains(text))
            return isFileNameText ? paths : text
        }
        if !snapshot.urls.isEmpty { return snapshot.urls.joined(separator: "\n") }
        return paths.isEmpty ? nil : paths
    }

    /// Unifies line endings to `\n` and trims surrounding whitespace.
    public static func normalize(_ text: String) -> String {
        text.replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .replacingOccurrences(of: "\u{2028}", with: "\n")
            .replacingOccurrences(of: "\u{2029}", with: "\n")
            .replacingOccurrences(of: "\u{85}", with: "\n")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Length checks on normalized text.
    public static func lengthSkip(of text: String, configuration: CaptureConfiguration)
        -> SkipReason?
    {
        if text.isEmpty { return .empty }
        let count = text.count
        if count < configuration.minimumLength { return .tooShort }
        if count > configuration.maximumLength { return .tooLong }
        return nil
    }
}

/// Turns one pasteboard snapshot into at most one stored copy.
public struct CapturePipeline: Sendable {
    private let store: ContentStore
    private let configuration: CaptureConfiguration
    private let detector: SecretDetector
    private let secretSink: (any SecretSink)?
    private let contextDetails: (any ContextDetailProviding)?
    /// Pause state and ignore rules this pipeline obeys.
    public let control: CaptureControl

    public init(
        store: ContentStore, configuration: CaptureConfiguration = CaptureConfiguration(),
        detector: SecretDetector = SecretDetector(), secretSink: (any SecretSink)? = nil,
        contextDetails: (any ContextDetailProviding)? = nil,
        control: CaptureControl = CaptureControl()
    ) {
        self.contextDetails = contextDetails
        self.control = control
        self.store = store
        self.configuration = configuration
        self.detector = detector
        self.secretSink = secretSink
    }

    public func process(
        _ snapshot: PasteboardSnapshot, source: CopyContext, at copiedAt: Date = Date()
    ) throws -> CaptureOutcome {
        try process(snapshot, sources: [source], at: copiedAt)
    }

    /// `sources` are the apps that may have made the copy, oldest first. If any of them is
    /// blocked the copy is dropped; otherwise it is attributed to the first one. Without a
    /// known app (no bundle identifier) the copy is kept.
    public func process(
        _ snapshot: PasteboardSnapshot, sources: [CopyContext], at copiedAt: Date = Date()
    ) throws -> CaptureOutcome {
        let pauseGeneration = control.pauseGeneration
        if control.isPaused { return .skipped(.paused) }
        var effective = configuration
        effective.blockedBundleIDs.formUnion(control.rules.apps)
        for candidate in sources {
            if let reason = CaptureStages.skipReason(
                for: snapshot, source: candidate, configuration: effective)
            {
                return .skipped(reason)
            }
        }
        let source = sources.first ?? CopyContext()
        guard let raw = CaptureStages.content(of: snapshot) else { return .skipped(.noText) }
        // Cheap bound before any copy of a possibly huge string is made.
        if raw.utf16.count > configuration.maximumLength * 4 { return .skipped(.tooLong) }
        let text = CaptureStages.normalize(raw)
        if let reason = CaptureStages.lengthSkip(of: text, configuration: configuration) {
            return .skipped(reason)
        }
        if control.matchesPattern(text) { return .skipped(.ignoredByRule) }
        if detector.containsSecret(in: text) {
            if control.isPaused || control.pauseGeneration != pauseGeneration {
                return .skipped(.paused)
            }
            secretSink?.handle(secret: text, context: source, copiedAt: copiedAt)
            return .skipped(.secret)
        }
        // Details are read last, so skipped copies never cost an accessibility or Apple Event call.
        // After an app switch inside the poll window the current window may belong to another app.
        let context = sources.count == 1 ? (contextDetails?.details(for: source) ?? source) : source
        // A pause clicked while details were being read still wins, even if capture was resumed
        // again before this point.
        if control.isPaused || control.pauseGeneration != pauseGeneration {
            return .skipped(.paused)
        }
        return .recorded(try store.record(text: text, copiedAt: copiedAt, context: context))
    }
}
